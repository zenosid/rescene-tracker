"""
X 게시물 중 '리센느 소식'이 아닌 거래·대행·스팸 글을 가려내는 필터.

실제 데이터(X 10,493건) 점검 결과: 그룹명은 모두 들어 있었지만 약 35%가
포카 양도/판매, 대리찍사·사후 데이터 판매, 팬싸컷 상담, 토토·매크로 광고처럼
여러 그룹 이름을 나열한 거래·광고 글이었습니다. 아래 '강한 신호'가 있을 때만 제외합니다.
('판매', '교환', '공구'처럼 공식 MD 판매 안내에도 쓰이는 단어는 자동 제외하지 않습니다.)
"""
import re

_STRONG = re.compile(
    r"대리\s?찍사|대리\s?캠|댈\s?찍|사후\s?데이터|팝니다|삽니다|양도|분철|팬싸\s?컷|급처|택포|"
    r"페이팔|paypal|오픈\s?카톡|구해요|구합니다|토토|매크로|성공초|공방\s?사녹|대리\s?티켓팅|댈구",
    re.I,
)
# 공식 공지의 '양도 불가/재판매 금지' 안내문구는 거래 글이 아니므로 판정 전에 지움
_NOTICE = re.compile(r"(?:양도|재판매|대리)[^.\n]{0,10}(?:불가|금지|제한|❌|X\b)")


def is_trading_or_spam(text):
    cleaned = _NOTICE.sub("", text or "")
    return _STRONG.search(cleaned) is not None
